-- 048_notification.sql
-- 알림 저장/조회를 위한 notifications 테이블 추가, users에 알림 설정 컬럼 3개 추가

alter table users
    add column notify_result boolean not null default true,
    add column notify_scrap boolean not null default true,
    add column notify_operator boolean not null default true;

create table notifications (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    type varchar(30) not null
        check (type in (
            'POSTING_NOTICE', 'DOC_RESULT', 'FINAL_RESULT', 'INTERVIEW_RESELECT', 'SCRAP_OPEN',
            'INVITATION', 'TRANSFER_REQUEST', 'TRANSFER_APPROVED', 'TRANSFER_REJECTED',
            'EVALUATION_REQUEST', 'EVALUATION_DEADLINE'
        )),
    organization_id bigint,
    -- message 도메인이 아직 없어 FK 없이 id만 저장 (B가 messages 테이블을 만들면 FK로 교체)
    message_id bigint,
    title varchar(200) not null,
    link_url varchar(500),
    is_read boolean not null default false,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_notifications_user_id foreign key (user_id) references users (id),
    constraint fk_notifications_organization_id foreign key (organization_id) references organizations (id)
);

create index idx_notifications_user_id_created_at on notifications (user_id, created_at);
