-- 학교 인증(#76): school_verifications 테이블 추가, 메일 도메인으로 학교 하나를 찾기 위한 unique index(DDL에만 있음)

create table school_verifications (
    id bigint generated by default as identity,
    user_id bigint not null,
    school_id bigint,
    method varchar(30) not null,
    email varchar(255),
    status varchar(30) not null,
    reject_reason varchar(500),
    reviewed_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

alter table school_verifications add constraint fk_school_verifications_user_id foreign key (user_id) references users;
alter table school_verifications add constraint fk_school_verifications_school_id foreign key (school_id) references schools;

create index if not exists idx_school_verifications_user_id on school_verifications(user_id);

