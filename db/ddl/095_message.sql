-- 095_message.sql
-- 서류 결과 안내 메시지(messages)와 지원자별 메일 전달 내역(message_deliveries) 테이블 추가.
-- 메시지는 (공고, type, target)마다 하나라 unique를 걸고, 한 메시지가 같은 지원서에 두 번 전달되지 않게 전달 내역에도 unique를 검

create table if not exists messages (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    sender_id bigint not null,
    type varchar(30) not null
        check (type in ('NOTICE', 'DOC_RESULT', 'INTERVIEW', 'FINAL_RESULT')),
    target varchar(30) not null
        check (target in ('ALL', 'PASS', 'FAIL')),
    subject varchar(100) not null,
    body varchar(1000) not null,
    status varchar(30) not null
        check (status in ('DRAFT', 'SENDING', 'SENT')),
    sent_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_messages_posting_id_type_target unique (posting_id, type, target),
    constraint fk_messages_posting_id foreign key (posting_id) references postings (id),
    constraint fk_messages_sender_id foreign key (sender_id) references users (id)
);

create table if not exists message_deliveries (
    id bigint generated by default as identity primary key,
    message_id bigint not null,
    application_id bigint not null,
    email varchar(100) not null,
    status varchar(30) not null
        check (status in ('PENDING', 'SUCCESS', 'FAILED')),
    fail_reason varchar(255),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_message_deliveries_message_id_application_id unique (message_id, application_id),
    constraint fk_message_deliveries_message_id foreign key (message_id) references messages (id),
    constraint fk_message_deliveries_application_id foreign key (application_id) references applications (id)
);

create index if not exists idx_message_deliveries_application_id on message_deliveries (application_id);
