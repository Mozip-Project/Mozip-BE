-- #69_application.sql
-- 지원서 임시 저장/제출/조회를 위한 applications 보강, attachments 테이블 추가.
-- baseline(#36)이 develop에 먼저 들어가면서 applications/answers가 이미 있어, applications에
-- 없는 컬럼만 alter로 추가하고 answers는 그대로 씀 (처음엔 baseline과 번호가 겹치는 파일로
-- 썼다가 충돌 때문에 alter 기반으로 다시 씀).
-- dev는 ddl-auto: update라 컬럼이 먼저 생길 수 있어 add column/index는 if not exists로 씀

alter table applications add column if not exists profile_snapshot text;
alter table applications add column if not exists available_times timestamp[];

create index if not exists idx_applications_user_id on applications (user_id);

create table if not exists attachments (
    id bigint generated by default as identity primary key,
    answer_id bigint not null,
    type varchar(10) not null
        check (type in ('FILE', 'LINK')),
    url varchar(500) not null,
    file_name varchar(255),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    -- answer를 통째로 재저장(삭제 후 재생성)할 때 같이 지워지게 cascade
    constraint fk_attachments_answer_id foreign key (answer_id) references answers (id) on delete cascade
);
