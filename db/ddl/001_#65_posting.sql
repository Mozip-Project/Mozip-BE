-- 001_#65_posting.sql
-- 공고 작성/게시/조회를 위한 postings 보강, positions/questions 보강, posting_images와
-- interview_time_ranges 테이블 추가. 이 저장소에 db/ddl이 아직 없어 postings/positions/questions는
-- 전체 테이블로 적음 (다른 브랜치의 알림 기능과 번호가 겹치면 머지 순서에 맞춰 둘 중 하나를 재번호)

create table postings (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    source_posting_id bigint,
    title varchar(100) not null,
    semester varchar(20),
    content text,
    status varchar(30) not null
        check (status in (
            'DRAFT', 'RECRUITING', 'DOC_REVIEW', 'DOC_RESULT_NOTICE', 'INTERVIEW', 'FINAL_RESULT', 'ENDED'
        )),
    draft_step integer,
    has_interview boolean not null default false,
    interview_method varchar(30) check (interview_method in ('ONSITE', 'ONLINE')),
    no_position boolean not null default false,
    region varchar(100),
    fee varchar(50),
    allow_enrolled boolean not null default true,
    allow_on_leave boolean not null default false,
    eligibility_note varchar(200),
    activity_started_on date,
    activity_ended_on date,
    publish_at timestamp(6),
    published_at timestamp(6),
    recruit_start_at timestamp(6),
    recruit_end_at timestamp(6),
    doc_result_at timestamp(6),
    final_result_at timestamp(6),
    -- TODO(B 서류 평가/면접): decideDocResult, decideFinalResult가 생기면 그쪽에서 채움
    doc_result_confirmed_at timestamp(6),
    final_result_confirmed_at timestamp(6),
    interview_minutes integer,
    break_minutes integer,
    assign_rule varchar(30) check (assign_rule in ('SAME_TEAM', 'ALL_MEMBERS')),
    max_applicants_per_interview integer,
    max_parallel_interviews integer,
    doc_score_per_question boolean,
    interview_score_per_question boolean,
    interview_guide text,
    -- TODO(B 면접): 타임테이블 확정 메서드가 생기면 그쪽에서 채움
    timetable_confirmed_at timestamp(6),
    view_count integer not null default 0,
    bumped_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_postings_organization_id foreign key (organization_id) references organizations (id),
    constraint fk_postings_source_posting_id foreign key (source_posting_id) references postings (id)
);

create index idx_postings_status_bumped_at on postings (status, bumped_at);

create table positions (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    team_id bigint,
    name varchar(50) not null,
    headcount integer,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_positions_posting_id foreign key (posting_id) references postings (id),
    constraint fk_positions_team_id foreign key (team_id) references teams (id)
);

create table questions (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    position_id bigint,
    type varchar(30) not null
        check (type in ('TEXT', 'SINGLE_CHOICE', 'MULTI_CHOICE', 'FILE_LINK', 'TABLE')),
    title varchar(200) not null,
    description varchar(500),
    -- TODO(B 서류 평가): 평가 화면 표에 쓸 짧은 제목, 아직 입력 경로 없음
    short_title varchar(50),
    required boolean not null default false,
    max_length integer,
    choices text[],
    columns text[],
    max_rows integer,
    max_files integer,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_questions_posting_id foreign key (posting_id) references postings (id),
    constraint fk_questions_position_id foreign key (position_id) references positions (id)
);

create table posting_images (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    url varchar(500) not null,
    is_representative boolean not null default false,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_posting_images_posting_id foreign key (posting_id) references postings (id)
);

create table interview_time_ranges (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    position_id bigint,
    date date not null,
    start_time time not null,
    end_time time not null,
    closed_slots time[],
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_interview_time_ranges_posting_id foreign key (posting_id) references postings (id),
    constraint fk_interview_time_ranges_position_id foreign key (position_id) references positions (id)
);
