-- 107_interview_timetable.sql
-- 면접 칸에 장소를 적을 수 있게 interviews.location 추가, 공고별 타임테이블 조회용 인덱스 (#107)

alter table interviews add column if not exists location varchar(100);

create index if not exists idx_interviews_posting_id on interviews (posting_id);

-- 공고별 타임테이블 상태. 면접실 열 개수와 확정 후 수정 모드 여부 (#107)
create table if not exists interview_timetable_states (
    id bigint generated by default as identity,
    posting_id bigint not null,
    track_count integer not null,
    editing_started_at timestamp(6),
    snapshot_track_count integer,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_interview_timetable_states_posting unique (posting_id)
);

-- 확정 후 수정 모드에 들어갈 때의 타임테이블 사본. 수정 취소하면 이걸로 되돌림 (#107)
create table if not exists interview_snapshots (
    id bigint generated by default as identity,
    posting_id bigint not null,
    start_at timestamp(6) not null,
    end_at timestamp(6) not null,
    track integer not null,
    location varchar(100),
    application_ids bigint[] not null,
    member_ids bigint[] not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create index if not exists idx_interview_snapshots_posting_id on interview_snapshots (posting_id);
