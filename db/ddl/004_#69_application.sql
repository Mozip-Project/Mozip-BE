-- 004_#69_application.sql
-- 지원서 임시 저장/제출/조회를 위한 applications, answers, attachments 테이블.
-- applications/answers는 이 저장소에 db/ddl이 아직 없어 전체 테이블로 적음 (이미 존재하는 엔티티라 컬럼이 더 많음)

create table applications (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    position_id bigint,
    user_id bigint not null,
    status varchar(30) not null
        check (status in ('DRAFT', 'SUBMITTED')),
    doc_result varchar(30) not null
        check (doc_result in ('PENDING', 'HOLD', 'PASS', 'FAIL')),
    final_result varchar(30) not null
        check (final_result in ('PENDING', 'PASS', 'FAIL')),
    submitted_at timestamp(6),
    -- 제출 시점 프로필 (JSON 문자열)
    profile_snapshot text,
    -- 면접 가능 시간 블록의 시작 시각 목록
    available_times timestamp[],
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_applications_posting_id foreign key (posting_id) references postings (id),
    constraint fk_applications_position_id foreign key (position_id) references positions (id),
    constraint fk_applications_user_id foreign key (user_id) references users (id),
    constraint uk_applications_posting_id_user_id unique (posting_id, user_id)
);

create index idx_applications_user_id on applications (user_id);

create table answers (
    id bigint generated by default as identity primary key,
    application_id bigint not null,
    question_id bigint not null,
    -- TEXT 답변, CHOICE / TABLE은 JSON 문자열
    content text,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_answers_application_id foreign key (application_id) references applications (id),
    constraint fk_answers_question_id foreign key (question_id) references questions (id)
);

create table attachments (
    id bigint generated by default as identity primary key,
    answer_id bigint not null,
    type varchar(10) not null
        check (type in ('FILE', 'LINK')),
    url varchar(500) not null,
    file_name varchar(255),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    -- answer를 통째로 재저장(삭제 후 재생성)할 때 같이 지워지게 cascade
    constraint fk_attachments_answer_id foreign key (answer_id) references answers (id) on delete cascade
);
