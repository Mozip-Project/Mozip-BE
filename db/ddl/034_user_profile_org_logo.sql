-- 단체 로고(presigned URL), 회원 프로필/알림 컬럼과 활동경험(experiences) 테이블 추가
-- 컬럼은 dev/prod에 이미 있을 수 있어 if not exists로 추가

alter table organizations add column if not exists logo_url varchar(500);

alter table users add column if not exists profile_image_url varchar(500);
alter table users add column if not exists department varchar(100);
alter table users add column if not exists grade integer;
alter table users add column if not exists contact_email varchar(100);
alter table users add column if not exists notify_result boolean not null default true;
alter table users add column if not exists notify_scrap boolean not null default true;
alter table users add column if not exists notify_operator boolean not null default true;

create table if not exists experiences (
    id bigint generated by default as identity,
    user_id bigint not null,
    title varchar(100) not null,
    role varchar(50),
    achievement varchar(200),
    started_on date,
    ended_on date,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

alter table experiences add constraint fk_experiences_user_id foreign key (user_id) references users;
