-- 2단계(포지션) 재저장으로 포지션이 통째로 교체돼도 지워지지 않게 하고, 끊어진 연결은 공통 문항으로 떨어뜨림
alter table questions drop constraint if exists fk_questions_position_id;
alter table questions add constraint fk_questions_position_id foreign key (position_id) references positions (id) on delete set null;

create table if not exists posting_images (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    url varchar(500) not null,
    is_representative boolean not null default false,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_posting_images_posting_id foreign key (posting_id) references postings (id)
);

create table if not exists interview_time_ranges (
    id bigint generated by default as identity primary key,
    posting_id bigint not null,
    position_id bigint,
    date date not null,
    start_time time not null,
    end_time time not null,
    closed_slots time[],
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_interview_time_ranges_posting_id foreign key (posting_id) references postings (id),
    -- 2단계(포지션) 재저장으로 포지션이 통째로 교체돼도 지워지지 않게 하고, 끊어진 연결은 전체 공통으로 떨어뜨림
    constraint fk_interview_time_ranges_position_id foreign key (position_id) references positions (id) on delete set null
);
