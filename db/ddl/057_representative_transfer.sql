-- 057_representative_transfer.sql
-- 대표자 인수(#57): 대표자가 운영진에게 요청하고 대상이 수락하면 역할을 바꿈
-- 동시에 두 요청이 들어와도 단체당 대기 요청이 1개만 남도록 PENDING 행에만 부분 unique index를 걺

create table representative_transfers (
    id bigint generated by default as identity,
    organization_id bigint not null,
    from_member_id bigint not null,
    to_member_id bigint not null,
    status varchar(20) not null check ((status in ('PENDING','APPROVED','REJECTED','CANCELED'))),
    responded_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

alter table representative_transfers add constraint fk_representative_transfers_organization_id foreign key (organization_id) references organizations;
alter table representative_transfers add constraint fk_representative_transfers_from_member_id foreign key (from_member_id) references members;
alter table representative_transfers add constraint fk_representative_transfers_to_member_id foreign key (to_member_id) references members;

create unique index uk_representative_transfers_pending on representative_transfers (organization_id) where status = 'PENDING';
