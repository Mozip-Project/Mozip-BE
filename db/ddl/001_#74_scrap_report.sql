-- 공고 스크랩/신고를 위한 scraps, reports 테이블. 이 브랜치의 db/ddl에는 아직 postings, users 테이블이 없어서
-- (다른 이슈 PR에서 추가될 예정) 여기서는 만들지 않고 FK만 걸어 둔다. 번호가 겹치면 머지 순서에 맞춰 재번호

create table scraps (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    posting_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_scraps_user_id foreign key (user_id) references users (id),
    constraint fk_scraps_posting_id foreign key (posting_id) references postings (id),
    constraint uk_scraps_user_id_posting_id unique (user_id, posting_id)
);

create table reports (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    posting_id bigint not null,
    reason varchar(30) not null
        check (reason in ('FALSE_INFO', 'INAPPROPRIATE', 'EXCESSIVE_PERSONAL_INFO', 'ETC')),
    detail text,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_reports_user_id foreign key (user_id) references users (id),
    constraint fk_reports_posting_id foreign key (posting_id) references postings (id),
    -- 같은 회원이 같은 공고를 두 번 신고할 수 없음
    constraint uk_reports_user_id_posting_id unique (user_id, posting_id)
);
