-- 단체 프로필(#38): 로고, 한 줄 소개, 소개, 메일 컬럼과 키워드/활동 분야/링크 테이블 추가
-- 키워드와 분야는 단체 안에서 중복 금지 (unique index). 키워드 접두 검색용 index는 like 'x%'가 타도록 varchar_pattern_ops

alter table organizations add column logo_url varchar(500);
alter table organizations add column tagline varchar(40);
alter table organizations add column description text;
alter table organizations add column email varchar(255);

create table organization_keywords (
    id bigint generated by default as identity,
    organization_id bigint not null,
    keyword varchar(30) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table organization_fields (
    id bigint generated by default as identity,
    organization_id bigint not null,
    field varchar(30) not null check ((field in ('ACADEMIC_STUDY','IT_DEV','DESIGN_MEDIA','PERFORMANCE_MUSIC','SPORTS','CULTURE_HOBBY','VOLUNTEER','LANGUAGE_GLOBAL','STARTUP_BUSINESS','RELIGION','ETC'))),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table organization_links (
    id bigint generated by default as identity,
    organization_id bigint not null,
    type varchar(30) not null check ((type in ('INSTAGRAM','WEBSITE','YOUTUBE','ETC'))),
    url varchar(500) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

alter table organization_keywords add constraint fk_organization_keywords_organization_id foreign key (organization_id) references organizations;
alter table organization_fields add constraint fk_organization_fields_organization_id foreign key (organization_id) references organizations;
alter table organization_links add constraint fk_organization_links_organization_id foreign key (organization_id) references organizations;

create unique index uk_organization_keywords_organization_keyword on organization_keywords (organization_id, keyword);
create unique index uk_organization_fields_organization_field on organization_fields (organization_id, field);
create index idx_organization_links_organization_id on organization_links (organization_id);
create index idx_organization_keywords_keyword on organization_keywords (keyword varchar_pattern_ops);
