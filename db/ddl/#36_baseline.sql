-- 이후 변경은 새 이슈번호로 파일을 추가하고, 운영 DB에는 배포 전 머지된 순서대로 수동 적용

create table answers (
    id bigint generated by default as identity,
    application_id bigint not null,
    question_id bigint not null,
    content TEXT,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table applications (
    id bigint generated by default as identity,
    position_id bigint,
    posting_id bigint not null,
    submitted_at timestamp(6),
    user_id bigint not null,
    doc_result varchar(30) not null check ((doc_result in ('PENDING','HOLD','PASS','FAIL'))),
    final_result varchar(30) not null check ((final_result in ('PENDING','PASS','FAIL'))),
    status varchar(30) not null check ((status in ('DRAFT','SUBMITTED'))),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (posting_id, user_id)
);

create table doc_evaluations (
    id bigint generated by default as identity,
    application_id bigint not null,
    member_id bigint not null,
    submitted_at timestamp(6),
    opinion varchar(30) check ((opinion in ('PASS','HOLD','FAIL'))),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (application_id, member_id)
);

create table interview_applicants (
    id bigint generated by default as identity,
    application_id bigint not null,
    interview_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (interview_id, application_id)
);

create table interview_evaluations (
    id bigint generated by default as identity,
    application_id bigint not null,
    member_id bigint not null,
    submitted_at timestamp(6),
    opinion varchar(30) check ((opinion in ('PASS','HOLD','FAIL'))),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (application_id, member_id)
);

create table interviewers (
    id bigint generated by default as identity,
    interview_id bigint not null,
    member_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (interview_id, member_id)
);

create table interviews (
    id bigint generated by default as identity,
    track integer not null,
    end_at timestamp(6) not null,
    posting_id bigint not null,
    start_at timestamp(6) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table members (
    id bigint generated by default as identity,
    organization_id bigint not null,
    team_id bigint,
    user_id bigint not null,
    role varchar(30) not null check ((role in ('REPRESENTATIVE','OPERATOR'))),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (organization_id, user_id)
);

create table organizations (
    id bigint generated by default as identity,
    no_team boolean not null,
    school_id bigint,
    review_status varchar(30) not null check ((review_status in ('PENDING','APPROVED','REJECTED'))),
    scope varchar(30) not null check ((scope in ('CAMPUS','UNION'))),
    type varchar(30) not null check ((type in ('CLUB','ACADEMIC','STUDENT_COUNCIL'))),
    name varchar(50) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table payments (
    id bigint generated by default as identity,
    amount integer not null,
    organization_id bigint not null,
    paid_at timestamp(6),
    user_id bigint not null,
    product varchar(30) not null check ((product in ('PACKAGE','UP_ONCE'))),
    status varchar(30) not null check ((status in ('PAID','REFUND_REQUESTED','REFUNDED','FAILED'))),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table positions (
    id bigint generated by default as identity,
    headcount integer,
    posting_id bigint not null,
    team_id bigint,
    name varchar(50) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table postings (
    id bigint generated by default as identity,
    has_interview boolean not null,
    no_position boolean not null,
    organization_id bigint not null,
    recruit_end_at timestamp(6),
    recruit_start_at timestamp(6),
    status varchar(30) not null check ((status in ('DRAFT','RECRUITING','DOC_REVIEW','DOC_RESULT_NOTICE','INTERVIEW','FINAL_RESULT','ENDED'))),
    title varchar(100) not null,
    content TEXT,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table questions (
    id bigint generated by default as identity,
    required boolean not null,
    sort_order integer not null,
    position_id bigint,
    posting_id bigint not null,
    type varchar(30) not null check ((type in ('TEXT','SINGLE_CHOICE','MULTI_CHOICE','FILE_LINK','TABLE'))),
    title varchar(255) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table reviewers (
    id bigint generated by default as identity,
    member_id bigint not null,
    position_id bigint,
    posting_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table schools (
    id bigint generated by default as identity,
    email_domain varchar(100),
    name varchar(100) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table scraps (
    id bigint generated by default as identity,
    posting_id bigint not null,
    user_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (user_id, posting_id)
);

create table teams (
    id bigint generated by default as identity,
    organization_id bigint not null,
    name varchar(50) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table users (
    id bigint generated by default as identity,
    marketing_agreed boolean not null,
    school_id bigint,
    terms_agreed_at timestamp(6) not null,
    authority varchar(20) not null check ((authority in ('USER','ADMIN'))),
    last_role varchar(20) not null check ((last_role in ('APPLICANT','OPERATOR'))),
    phone varchar(20) not null unique,
    status varchar(20) not null check ((status in ('ACTIVE','LOCKED','WITHDRAWN'))),
    name varchar(50) not null,
    password varchar(255) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

