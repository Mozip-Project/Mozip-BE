-- 운영진 초대/팀 관리(#56): 개인 초대, 공용 초대 링크 테이블과 팀 표시 순서
-- 초대 코드와 링크 토큰은 수락 시 이 값 하나로 찾으므로 unique. 대기 중 초대 중복은 만료 여부까지 봐야 해서 서비스에서 막음

alter table teams add column sort_order integer not null default 0;

create table invitations (
    id bigint generated by default as identity,
    organization_id bigint not null,
    inviter_id bigint not null,
    invitee_id bigint,
    invitee_contact varchar(255) not null,
    team_id bigint,
    code varchar(64) not null unique,
    status varchar(20) not null check ((status in ('PENDING','ACCEPTED','DECLINED','CANCELED'))),
    expires_at timestamp(6) not null,
    responded_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table invite_links (
    id bigint generated by default as identity,
    organization_id bigint not null,
    token varchar(64) not null unique,
    expires_at timestamp(6) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

alter table invitations add constraint fk_invitations_organization_id foreign key (organization_id) references organizations;
alter table invitations add constraint fk_invitations_inviter_id foreign key (inviter_id) references users;
alter table invitations add constraint fk_invitations_invitee_id foreign key (invitee_id) references users;
alter table invitations add constraint fk_invitations_team_id foreign key (team_id) references teams;
alter table invite_links add constraint fk_invite_links_organization_id foreign key (organization_id) references organizations;

create index idx_invitations_organization_contact on invitations (organization_id, invitee_contact);
create index idx_invite_links_organization_id on invite_links (organization_id);
